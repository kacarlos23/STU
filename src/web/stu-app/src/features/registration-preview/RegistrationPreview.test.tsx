import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import '@testing-library/jest-dom/vitest'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { RegistrationPreview } from './RegistrationPreview'

afterEach(() => { cleanup(); vi.unstubAllGlobals() })

function openAgent() {
  fireEvent.click(screen.getByRole('button', { name: 'Abrir Microrregião 01' }))
  fireEvent.click(screen.getByRole('button', { name: 'Consultar endereços de Mariana Alves' }))
}
function startAddress() {
  openAgent()
  fireEvent.click(screen.getByRole('button', { name: 'Cadastrar endereço' }))
  fireEvent.change(screen.getByLabelText('Logradouro *'), { target: { value: 'Rua de teste' } })
  fireEvent.change(screen.getByLabelText('Número *'), { target: { value: '200' } })
  fireEvent.click(screen.getByRole('button', { name: 'Continuar para família' }))
}

describe('Prévia da hierarquia de cadastro', () => {
  it('percorre microrregião, agente, endereço e família sem consultar APIs', () => {
    const fetch = vi.fn()
    vi.stubGlobal('fetch', fetch)
    render(<RegistrationPreview />)
    expect(screen.getByRole('heading', { level: 1, name: 'Microrregiões' })).toBeInTheDocument()
    openAgent()
    expect(screen.getByText('Rua das Acácias, 120')).toBeInTheDocument()
    expect(screen.queryByText('Rua das Flores, 82')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Consultar família 001' }))
    expect(screen.getByRole('heading', { level: 1, name: 'Família 001' })).toBeInTheDocument()
    expect(screen.getByText('Ana Souza')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Endereços' }))
    expect(screen.getByRole('heading', { level: 1, name: 'Endereços de Mariana Alves' })).toBeInTheDocument()
    expect(fetch).not.toHaveBeenCalled()
  })

  it('só cria o endereço e a família depois da conferência final', () => {
    render(<RegistrationPreview />)
    startAddress()
    fireEvent.change(screen.getByLabelText('Número da família *'), { target: { value: '008' } })
    fireEvent.change(screen.getByLabelText('Responsável pela família *'), { target: { value: 'Ana-María D’Ávila' } })
    fireEvent.click(screen.getByRole('button', { name: 'Conferir cadastro' }))
    expect(within(screen.getByRole('dialog')).getByText('008 · Ana-María D’Ávila')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Salvar endereço e família' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByRole('heading', { level: 1, name: 'Família 008' })).toBeInTheDocument()
    expect(screen.getByText('Ana-María D’Ávila')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Endereços' }))
    expect(screen.getByText('Rua de teste, 200')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Consultar família 008' })).toBeInTheDocument()
  })

  it('vincula somente uma família disponível sem alterar outra família', () => {
    render(<RegistrationPreview />)
    startAddress()
    fireEvent.click(screen.getByRole('button', { name: 'Família existente' }))
    const selection = screen.getByRole('combobox', { name: /Família sem endereço vinculado/ })
    expect(within(selection).queryByRole('option', { name: '001 · Ana Souza' })).not.toBeInTheDocument()
    fireEvent.change(selection, { target: { value: 'f7' } })
    fireEvent.click(screen.getByRole('button', { name: 'Conferir cadastro' }))
    fireEvent.click(screen.getByRole('button', { name: 'Salvar endereço e família' }))
    expect(screen.getByRole('heading', { level: 1, name: 'Família 007' })).toBeInTheDocument()
    expect(screen.getByText('Helena Costa')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Endereços' }))
    fireEvent.click(screen.getByRole('button', { name: 'Consultar família 001' }))
    expect(screen.getByText('Ana Souza')).toBeInTheDocument()
  })

  it('impede número de família duplicado e descarta cadastro cancelado', () => {
    render(<RegistrationPreview />)
    startAddress()
    fireEvent.change(screen.getByLabelText('Número da família *'), { target: { value: '001' } })
    fireEvent.change(screen.getByLabelText('Responsável pela família *'), { target: { value: 'Outro responsável' } })
    fireEvent.click(screen.getByRole('button', { name: 'Conferir cadastro' }))
    expect(screen.getByRole('alert')).toHaveTextContent('Este número de família já existe')
    fireEvent.click(screen.getByRole('button', { name: 'Fechar formulário' }))
    expect(screen.queryByText('Rua de teste, 200')).not.toBeInTheDocument()
    expect(screen.queryByText('Outro responsável')).not.toBeInTheDocument()
  })

  it('encadeia nova microrregião, vínculo de agente e lista vazia de endereços', () => {
    render(<RegistrationPreview />)
    fireEvent.click(screen.getByRole('button', { name: 'Nova microrregião' }))
    fireEvent.change(screen.getByLabelText('Código *'), { target: { value: 'mr04' } })
    fireEvent.change(screen.getByLabelText('Nome da microrregião *'), { target: { value: 'Microrregião 04' } })
    fireEvent.change(screen.getByRole('combobox', { name: 'Bairro *' }), { target: { value: 'b2' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar e continuar para agentes' }))
    expect(screen.getByText(/Esta microrregião ainda não tem agentes/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Vincular agente' }))
    fireEvent.change(screen.getByLabelText('Agente da UBS *'), { target: { value: 'u5' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByRole('heading', { level: 1, name: 'Agentes da Microrregião 04' })).toBeInTheDocument()
    expect(screen.queryByRole('heading', { level: 1, name: 'Endereços de Juliana Costa' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Consultar endereços de Juliana Costa' }))
    expect(screen.getByRole('heading', { level: 1, name: 'Endereços de Juliana Costa' })).toBeInTheDocument()
    expect(screen.getByText(/Nenhum endereço cadastrado para este agente/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Cadastrar endereço' }))
    expect(screen.getByLabelText('Bairro *')).toHaveValue('Bairro de demonstração B')
  })

  it('exige a seleção de um bairro cadastrado para criar uma microrregião', () => {
    render(<RegistrationPreview />)
    fireEvent.click(screen.getByRole('button', { name: 'Nova microrregião' }))
    const neighborhood = screen.getByRole('combobox', { name: 'Bairro *' })
    expect(neighborhood).toHaveValue('')
    expect(neighborhood).toBeRequired()
    expect(within(neighborhood).getAllByRole('option')).toHaveLength(4)
    expect(within(neighborhood).getByRole('option', { name: 'Bairro de demonstração A' })).toHaveValue('b1')
    expect(within(neighborhood).getByRole('option', { name: 'Bairro de demonstração B' })).toHaveValue('b2')
    expect(within(neighborhood).getByRole('option', { name: 'Bairro de demonstração C' })).toHaveValue('b3')
    fireEvent.change(screen.getByLabelText('Código *'), { target: { value: 'MR04' } })
    fireEvent.change(screen.getByLabelText('Nome da microrregião *'), { target: { value: 'Microrregião 04' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar e continuar para agentes' }))
    expect(screen.getByRole('dialog')).toBeInTheDocument()
    expect(screen.queryByRole('heading', { level: 1, name: 'Agentes da Microrregião 04' })).not.toBeInTheDocument()
    fireEvent.change(neighborhood, { target: { value: 'b3' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar e continuar para agentes' }))
    expect(screen.getByRole('heading', { level: 1, name: 'Agentes da Microrregião 04' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Editar microrregião' }))
    expect(screen.getByRole('combobox', { name: 'Bairro *' })).toHaveValue('b3')
  })

  it('salva um novo agente e fecha o modal mantendo a equipe da microrregião', () => {
    render(<RegistrationPreview />)
    fireEvent.click(screen.getByRole('button', { name: 'Abrir Microrregião 02' }))
    fireEvent.click(screen.getByRole('button', { name: 'Vincular agente' }))
    fireEvent.click(screen.getByRole('button', { name: 'Cadastrar novo' }))
    fireEvent.change(screen.getByLabelText('Nome completo *'), { target: { value: 'Agente de teste' } })
    fireEvent.change(screen.getByLabelText('Usuário de acesso *'), { target: { value: 'agente.teste' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByRole('heading', { level: 1, name: 'Agentes da Microrregião 02' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Consultar endereços de Agente de teste' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Consultar endereços de Renata Lima' })).toBeInTheDocument()
    expect(screen.queryByRole('heading', { level: 1, name: 'Endereços de Agente de teste' })).not.toBeInTheDocument()
    expect(screen.getByRole('status')).toHaveTextContent('Agente vinculado à microrregião')
  })

  it('mantém o bairro selecionado ao editar uma microrregião existente', () => {
    render(<RegistrationPreview />)
    fireEvent.click(screen.getByRole('button', { name: 'Abrir Microrregião 01' }))
    fireEvent.click(screen.getByRole('button', { name: 'Editar microrregião' }))
    const neighborhood = screen.getByRole('combobox', { name: 'Bairro *' })
    expect(neighborhood).toHaveValue('b1')
    fireEvent.change(neighborhood, { target: { value: 'b2' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar alterações' }))
    fireEvent.click(screen.getByRole('button', { name: 'Editar microrregião' }))
    expect(screen.getByRole('combobox', { name: 'Bairro *' })).toHaveValue('b2')
    expect(screen.getByLabelText('Código *')).toHaveValue('MR01')
  })

  it('permite cancelar a desvinculação sem alterar os endereços do agente', () => {
    render(<RegistrationPreview />)
    fireEvent.click(screen.getByRole('button', { name: 'Abrir Microrregião 01' }))
    fireEvent.click(screen.getByRole('button', { name: 'Desvincular Mariana Alves' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('Este agente possui 3 endereços')
    fireEvent.click(screen.getByRole('button', { name: 'Cancelar' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Consultar endereços de Mariana Alves' }))
    expect(screen.getByRole('button', { name: 'Consultar família 001' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Consultar família 002' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Consultar família 003' })).toBeInTheDocument()
  })

  it('desvincula somente da microrregião selecionada e permite vincular novamente', () => {
    render(<RegistrationPreview />)
    fireEvent.click(screen.getByRole('button', { name: 'Abrir Microrregião 02' }))
    fireEvent.click(screen.getByRole('button', { name: 'Vincular agente' }))
    fireEvent.change(screen.getByLabelText('Agente da UBS *'), { target: { value: 'u1' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar' }))
    fireEvent.click(screen.getByRole('button', { name: 'Desvincular Mariana Alves' }))
    expect(screen.queryByRole('combobox', { name: 'Novo agente responsável *' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Desvincular' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByRole('heading', { level: 1, name: 'Agentes da Microrregião 02' })).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Consultar endereços de Mariana Alves' })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Consultar endereços de Renata Lima' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Vincular agente' }))
    expect(within(screen.getByLabelText('Agente da UBS *')).getByRole('option', { name: 'Mariana Alves' })).toHaveValue('u1')
    fireEvent.change(screen.getByLabelText('Agente da UBS *'), { target: { value: 'u1' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar' }))
    expect(screen.getAllByRole('button', { name: 'Consultar endereços de Mariana Alves' })).toHaveLength(1)
    fireEvent.click(within(screen.getByRole('navigation', { name: 'Navegação principal' })).getByRole('button', { name: 'Microrregiões' }))
    openAgent()
    expect(screen.getByRole('button', { name: 'Consultar família 001' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Consultar família 002' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Consultar família 003' })).toBeInTheDocument()
  })

  it('transfere todos os endereços preservando as famílias antes de desvincular', () => {
    render(<RegistrationPreview />)
    fireEvent.click(screen.getByRole('button', { name: 'Abrir Microrregião 01' }))
    fireEvent.click(screen.getByRole('button', { name: 'Desvincular Mariana Alves' }))
    const recipient = screen.getByRole('combobox', { name: 'Novo agente responsável *' })
    expect(within(recipient).getAllByRole('option')).toHaveLength(2)
    expect(within(recipient).queryByRole('option', { name: 'Renata Lima' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Desvincular' }))
    expect(screen.getByRole('dialog')).toBeInTheDocument()
    fireEvent.change(recipient, { target: { value: 'a2' } })
    fireEvent.click(screen.getByRole('button', { name: 'Desvincular' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByRole('heading', { level: 1, name: 'Agentes da Microrregião 01' })).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Desvincular Mariana Alves' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Consultar endereços de Carlos Santos' }))
    for (const number of ['001', '002', '003', '004']) {
      expect(screen.getByRole('button', { name: `Consultar família ${number}` })).toBeInTheDocument()
    }
    fireEvent.click(screen.getByRole('button', { name: 'Consultar família 001' }))
    expect(screen.getByText('Ana Souza')).toBeInTheDocument()
    expect(screen.getByText('Rua das Acácias, 120')).toBeInTheDocument()
    expect(screen.getByText('Carlos Santos', { selector: 'strong' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'MR01' }))
    fireEvent.click(screen.getByRole('button', { name: 'Vincular agente' }))
    fireEvent.change(screen.getByLabelText('Agente da UBS *'), { target: { value: 'u1' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar' }))
    fireEvent.click(screen.getByRole('button', { name: 'Consultar endereços de Mariana Alves' }))
    expect(screen.getByText(/Nenhum endereço cadastrado para este agente/)).toBeInTheDocument()
  })

  it('preserva os cadastros quando o único agente da microrregião tem endereços', () => {
    render(<RegistrationPreview />)
    fireEvent.click(screen.getByRole('button', { name: 'Abrir Microrregião 02' }))
    fireEvent.click(screen.getByRole('button', { name: 'Desvincular Renata Lima' }))
    expect(screen.getByRole('button', { name: 'Desvincular' })).toBeDisabled()
    expect(screen.getByRole('dialog')).toHaveTextContent('Vincule outro agente à microrregião')
    fireEvent.click(screen.getByRole('button', { name: 'Cancelar' }))
    fireEvent.click(screen.getByRole('button', { name: 'Consultar endereços de Renata Lima' }))
    expect(screen.getByText('Rua do Sol, 16')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Consultar família 005' })).toBeInTheDocument()
  })

  it('edita família e endereço separadamente e permite consulta sem acentos', () => {
    render(<RegistrationPreview />)
    openAgent()
    fireEvent.change(screen.getByRole('searchbox', { name: 'Buscar endereço ou família' }), { target: { value: 'jose' } })
    expect(screen.getByRole('button', { name: 'Consultar família 002' })).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Consultar família 001' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Consultar família 002' }))
    fireEvent.click(screen.getByRole('button', { name: 'Editar família' }))
    fireEvent.change(screen.getByLabelText('Responsável pela família *'), { target: { value: 'José da Silva' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar família' }))
    expect(screen.getByText('José da Silva')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Editar endereço' }))
    fireEvent.click(screen.getByLabelText('Sem número'))
    fireEvent.click(screen.getByRole('button', { name: 'Salvar endereço' }))
    expect(screen.getByText('Rua das Acácias, s/n')).toBeInTheDocument()
    expect(screen.getByText('José da Silva')).toBeInTheDocument()
  })
})
